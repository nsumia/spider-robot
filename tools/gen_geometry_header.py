#!/usr/bin/env python3
"""Generate firmware/spider/src/geometry_gen.h from cad/out/leg_geometry.json (single source of truth).
Usage: gen_geometry_header.py [--check]   (--check: exit 1 if the committed header differs)"""
import json, os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "cad", "out", "leg_geometry.json")
DST = os.path.join(ROOT, "firmware", "spider", "src", "geometry_gen.h")


def f(x):
    return repr(float(x)) + "f"


def build():
    g = json.load(open(SRC))
    names = g["leg_names"]
    hips = {h["name"]: h for h in g["hips"]}
    tab = g["foot_table"]
    qs = [t["q"] for t in tab]
    assert qs == list(range(qs[0], qs[0] + len(qs))), "foot_table must have 1 deg steps"
    L = []
    a = L.append
    a("// GENERATED by tools/gen_geometry_header.py from cad/out/leg_geometry.json -- DO NOT EDIT.")
    a("#pragma once")
    a("namespace geom {")
    a(f"static const int kLegs = {len(names)};")
    a("// leg order: " + ", ".join(names))
    a("static const float kHipX[kLegs] = {" + ", ".join(f(hips[n]["xy"][0]) for n in names) + "};")
    a("static const float kHipY[kLegs] = {" + ", ".join(f(hips[n]["xy"][1]) for n in names) + "};")
    a("static const float kHeadingDeg[kLegs] = {" + ", ".join(f(hips[n]["heading_deg"]) for n in names) + "};")
    a(f"static const float kCoxaDegMin = {f(g['limits_deg']['coxa'][0])}, kCoxaDegMax = {f(g['limits_deg']['coxa'][1])};")
    a(f"static const float kFemurDegMin = {f(g['limits_deg']['femur'][0])}, kFemurDegMax = {f(g['limits_deg']['femur'][1])};")
    a(f"static const float kCoxaServoAbsMin = {f(g['servo_limits_deg_absolute']['coxa'][0])}, kCoxaServoAbsMax = {f(g['servo_limits_deg_absolute']['coxa'][1])};")
    a(f"static const float kFemurServoAbsMin = {f(g['servo_limits_deg_absolute']['femur'][0])}, kFemurServoAbsMax = {f(g['servo_limits_deg_absolute']['femur'][1])};")
    a(f"static const float kCoxaServoZero = {f(g['servo_zero_deg']['coxa'])}, kFemurServoZero = {f(g['servo_zero_deg']['femur'])};")
    a(f"static const int kCoxaSign = {int(g['servo_sign']['coxa'])}, kFemurSign = {int(g['servo_sign']['femur'])};  // assumed, UNVERIFIED")
    a(f"static const float kRideHeight = {f(g['neutral']['ride_height_body_underside_to_ground'])};")
    a(f"static const float kBodyHeight = {f(g['body']['height'])};")
    a(f"// foot contact point (leg-local r,z) vs femur angle q, {len(tab)} entries, 1 deg step from kTableQ0")
    a(f"static const int kTableQ0 = {qs[0]}, kTableN = {len(tab)};")
    a("static const float kFootR[kTableN] = {" + ", ".join(f(t["foot_contact"][0]) for t in tab) + "};")
    a("static const float kFootZ[kTableN] = {" + ", ".join(f(t["foot_contact"][1]) for t in tab) + "};")
    a("}  // namespace geom")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    txt = build()
    if "--check" in sys.argv:
        cur = open(DST).read() if os.path.exists(DST) else ""
        if cur != txt:
            print("FAIL: geometry_gen.h is out of date; run tools/gen_geometry_header.py")
            sys.exit(1)
        print("PASS: geometry_gen.h up to date with leg_geometry.json")
    else:
        open(DST, "w").write(txt)
        print("wrote", DST)
